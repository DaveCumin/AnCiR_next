    Biological rhythms are classified by <a class="gloss" href="#gloss-period">period</a> length. <a class="gloss" href="#gloss-circadian-rhythm"><strong
      >Circadian</strong
    ></a>
    rhythms (Latin:
    <em>circa diem</em>, 'about a day') have periods of ~24 hours.
    <a class="gloss" href="#gloss-ultradian"><strong>Ultradian</strong></a>
    rhythms are shorter than 24 hours (e.g., REM sleep cycles ~90 min);
    <a class="gloss" href="#gloss-infradian"><strong>infradian</strong></a> rhythms are longer (e.g., menstrual cycle ~28 days).
  </p>

