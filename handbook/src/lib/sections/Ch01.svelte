  <h3 class="section-head">The Circadian Clock</h3>
  <p>
    Circadian rhythms are generated by endogenous molecular clocks present in
    virtually every cell. In mammals, the master pacemaker is the <a class="gloss" href="#gloss-scn"><strong
      >suprachiasmatic nucleus (SCN)</strong
    ></a> of the anterior hypothalamus. The molecular clockwork is built on a transcription-translation
    feedback loop (a process where proteins made from a gene gradually switch that
    same gene off, creating a ~24-hour cycle):
  </p>

  <ul>
    <li>
      <strong>CLOCK</strong> and <strong>BMAL1</strong> drive transcription of
      <em>Period (PER1/2/3)</em> and <em>Cryptochrome (CRY1/2)</em> genes.
    </li>
    <li>
      PER and CRY proteins accumulate over several hours, then feed back to
      inhibit CLOCK/BMAL1 activity.
    </li>
    <li>
      As PER and CRY are degraded (~24 hours), CLOCK/BMAL1-driven transcription
      restarts.
    </li>
    <li>
      Secondary stabilising loops involving REV-ERBα/β and RORα add robustness.
    </li>
  </ul>
  <NoteBox title="Key Point">
    <p>
      The intrinsic period (<a class="gloss" href="#gloss-free-running-period">free-running period, τ</a>) is rarely exactly 24 hours —
      in humans the average is ~24.2 hours<sup class="cite"><a href="#ref-17">[17]</a></sup>. Daily synchronisation (<a class="gloss" href="#gloss-entrainment">entrainment</a>)
      requires external time cues called <a class="gloss" href="#gloss-zeitgeber"><strong>zeitgebers</strong></a>.
    </p>
  </NoteBox>

