  <h3 class="section-head">Zeitgebers and Entrainment</h3>
  <p>
    Zeitgebers (German: "time-givers") synchronise the internal clock to the
    external world.
    <strong>Light</strong> is the dominant zeitgeber, acting via intrinsically photosensitive
    retinal ganglion cells (ipRGCs) and the retinohypothalamic tract. Non-photic
    zeitgebers include:
  </p>
  <ul>
    <li>
      <strong>Feeding/fasting cycles</strong> — entrain peripheral clocks (liver,
      gut, adipose tissue) via metabolic signals.
    </li>
    <li>
      <strong>Exercise</strong> — acute physical activity can phase-shift the circadian
      system, timing-dependently.
    </li>
    <li>
      <strong>Temperature</strong> — the primary zeitgeber for many organisms; also
      influences mammalian peripheral clocks.
    </li>
    <li>
      <strong>Social cues</strong> — mealtimes, work schedules, and social interactions
      contribute to human circadian timing.
    </li>
  </ul>

  <h3 class="section-head">Why Circadian Biology Matters</h3>
  <h4 class="sub-head">Clinical and Medical Importance</h4>
  <p>
    Circadian disruption — from shift work, jet lag, hospitalisation, or social
    misalignment — has broad health consequences: elevated risk of obesity and
    type 2 diabetes in shift workers; morning peaks in myocardial infarction and
    stroke; associations between shift work and breast, colorectal, and prostate
    cancer (IARC Group 2A carcinogen). In perioperative medicine, surgery and
    ICU care disrupt circadian rhythms through light exposure, fasting,
    sedation, and inflammation, contributing to delirium, immune impairment, and
    delayed recovery.
  </p>

  <h4 class="sub-head">Chronopharmacology and Precision Medicine</h4>
  <p>
    Drug efficacy and toxicity vary with time of administration. Examples:
    evening dosing of ACE inhibitors better suppresses nocturnal blood pressure;
    timed delivery of oxaliplatin and 5-fluorouracil improves chemotherapy
    tolerability; short-acting statins are more effective taken at night when
    hepatic cholesterol synthesis peaks.
  </p>

  <h4 class="sub-head">Research Perspective</h4>
  <p>
    Circadian data are inherently time-structured. Standard statistical methods
    that ignore temporal ordering can give misleading results. This handbook
    provides the foundation to choose the right analysis, estimate parameters
    with appropriate uncertainty, compare rhythms between conditions, and use
    open-source tools reproducibly.
  </p>
