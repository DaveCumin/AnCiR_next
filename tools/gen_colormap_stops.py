#!/usr/bin/env python3
"""
Generate src/lib/components/plotbits/colormapStops.json: the colormap stop tables the app
interpolates (components/plotbits/colormaps.js colormapRGB), sampled from matplotlib so the
app's maps ARE matplotlib's maps (colour-by plan 2026-10-20, section 3.4).

  - viridis, magma, twilight_shifted: matplotlib.colormaps[name](t) at t = i / 64,
    i = 0..64 (65 stops), rounded to 0..255. 65 stops keep linear interpolation within
    1/255 of matplotlib at every colour-bucket centre (9 stops were up to 18/255 off).
  - twilight_shifted is cyclic: its LAST stop is set to its FIRST. matplotlib's 510-entry
    table ends one step short of closing the loop (cm(0) = (48, 20, 55), cm(1) =
    (47, 20, 54)), and the app needs 0 h and 24 h to be the same colour exactly.
  - greysCyclic: the monochrome twin of twilight_shifted, a grey of the same relative
    luminance at every stop (sRGB -> linear, Y = 0.2126 R + 0.7152 G + 0.0722 B, IEC
    61966-2-1 transfer function), so a monochrome print keeps the same dark-midnight,
    light-noon pattern.
  - reference.bucketCentres: matplotlib's own colour at each of the 64 bucket centres
    t = (b + 0.5) / 64, which the tests compare the interpolated app colours against.

tools/test_colormap_stops.py checks the file still equals what this script produces.

    tools/.venv/bin/python tools/gen_colormap_stops.py
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "src" / "lib" / "components" / "plotbits" / "colormapStops.json"

SAMPLED = ("viridis", "magma", "twilight_shifted")
CYCLIC = ("twilight_shifted",)
N_STOPS = 65
BUCKETS = 64


def rgb255(c):
    return [int(round(v * 255)) for v in c[:3]]


def srgb_to_linear(v):
    v = v / 255
    return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4


def linear_to_srgb(y):
    v = 12.92 * y if y <= 0.0031308 else 1.055 * y ** (1 / 2.4) - 0.055
    return int(round(max(0.0, min(1.0, v)) * 255))


def luminance_grey(rgb):
    r, g, b = (srgb_to_linear(v) for v in rgb)
    y = 0.2126 * r + 0.7152 * g + 0.0722 * b
    grey = linear_to_srgb(y)
    return [grey, grey, grey]


def build():
    stops = {}
    centres = {}
    for name in SAMPLED:
        cm = matplotlib.colormaps[name]
        table = [rgb255(cm(i / (N_STOPS - 1))) for i in range(N_STOPS)]
        if name in CYCLIC:
            table[-1] = list(table[0])
        stops[name] = table
        centres[name] = [rgb255(cm((b + 0.5) / BUCKETS)) for b in range(BUCKETS)]
    stops["greysCyclic"] = [luminance_grey(c) for c in stops["twilight_shifted"]]
    return {
        "_comment": "Generated by tools/gen_colormap_stops.py from matplotlib; do not edit.",
        "matplotlib": matplotlib.__version__,
        "stops": stops,
        "reference": {"buckets": BUCKETS, "bucketCentres": centres},
    }


def render(data):
    """One [r, g, b] per line, so prettier leaves the file as written and diffs stay small."""
    lines = ["{"]
    lines.append(f'\t"_comment": {json.dumps(data["_comment"])},')
    lines.append(f'\t"matplotlib": {json.dumps(data["matplotlib"])},')

    def table_block(indent, obj):
        out = []
        names = list(obj)
        for i, name in enumerate(names):
            rows = obj[name]
            out.append(f'{indent}"{name}": [')
            for j, row in enumerate(rows):
                out.append(f'{indent}\t[{row[0]}, {row[1]}, {row[2]}]' + ("," if j < len(rows) - 1 else ""))
            out.append(f'{indent}]' + ("," if i < len(names) - 1 else ""))
        return out

    lines.append('\t"stops": {')
    lines += table_block("\t\t", data["stops"])
    lines.append("\t},")
    lines.append('\t"reference": {')
    lines.append(f'\t\t"buckets": {data["reference"]["buckets"]},')
    lines.append('\t\t"bucketCentres": {')
    lines += table_block("\t\t\t", data["reference"]["bucketCentres"])
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(render(build()))
    print(f"wrote {OUT}")
